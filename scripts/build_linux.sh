#!/bin/bash
set -e

echo "==================================================="
echo "BitRun — Linux Native Build (GCC/Clang + Go)"
echo "Target: linux-amd64 (AVX2 / AVX-512)"
echo "==================================================="

PROJECT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$PROJECT_ROOT"

# Check prerequisites
export PATH="$HOME/.local/go/bin:/usr/local/go/bin:$PATH"
command -v cmake >/dev/null 2>&1 || { echo "[ERROR] cmake not found on PATH. Run: sudo apt install cmake build-essential"; exit 1; }
command -v go >/dev/null 2>&1 || { echo "[ERROR] go not found on PATH. Run: sudo apt install golang-go"; exit 1; }

mkdir -p bin

# 1. Build Native C++ Engine
echo "[1/3] Configuring CMake for Native BitNet C++ Engine..."
if [ ! -d "upstream/bitnet" ]; then
    echo "[INFO] Cloning BitRun engine (bitrun-engine branch) from GitHub..."
    git clone --depth 1 -b bitrun-engine --recursive https://github.com/IshekKhal/BitNet.git upstream/bitnet
fi
cd upstream/bitnet

# If CMakeCache was generated by Windows MSVC, clean it
if [ -f "build/CMakeCache.txt" ] && grep -qi "Visual Studio\|MSVC\|Program Files" build/CMakeCache.txt 2>/dev/null; then
    echo "[INFO] Cleaning prior Windows CMake build cache..."
    rm -rf build
fi

NUM_CORES=$(nproc 2>/dev/null || echo 4)

cmake -B build -DGGML_AVX2=ON -DBUILD_SHARED_LIBS=OFF -DCMAKE_BUILD_TYPE=Release -DLLAMA_BUILD_COMMON=ON -DLLAMA_BUILD_TOOLS=ON -DLLAMA_BUILD_SERVER=ON -DLLAMA_CURL=OFF
cmake --build build --config Release --target llama-cli llama-server llama-quantize -j "$NUM_CORES"

cd "$PROJECT_ROOT"

# Copy compiled binaries to bin/
cp upstream/bitnet/build/bin/llama-cli bin/
cp upstream/bitnet/build/bin/llama-server bin/
cp upstream/bitnet/build/bin/llama-quantize bin/

# 2. Compile Go Supervisor
echo "[2/3] Compiling Go Supervisor (bitrun)..."
go build -ldflags="-s -w" -o bin/bitrun main.go

echo "==================================================="
echo "[SUCCESS] BitRun Linux build complete!"
echo "Binaries ready in bin/"
echo "Test: ./bin/bitrun hardware"
echo "==================================================="
